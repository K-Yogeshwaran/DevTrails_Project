def find_nearest_zone(lat, lon):
    """
    Given GPS coordinates, returns the nearest zone_id from INDIA_ZONES.
    Uses Euclidean distance on lat/lon — accurate enough for zone snapping.
    """
    import math
    best_zone = None
    best_dist = float("inf")

    for zone_id, zone in INDIA_ZONES.items():
        dist = math.sqrt(
            (lat - zone["lat"]) ** 2 +
            (lon - zone["lon"]) ** 2
        )
        if dist < best_dist:
            best_dist = dist
            best_zone = zone_id

    return best_zone


